// Value checks shared by the log, span and metric serialisers. Each check accepts `unknown` because values
// reach the serialisers from instrumentation libraries and untyped callers as well as from typed code.

/**
 * Stands in for the Tenant id when work has no Tenant: platform jobs such as the outbox relay, or a request
 * rejected before its Tenant was resolved (1.3). Logs, metrics and spans then still carry a Tenant field (25.1).
 */
export const NO_TENANT = 'none';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Crockford base32 ULID. The first character is at most 7 because a ULID holds 128 bits. */
const ULID = /^[0-7][0-9A-HJKMNP-TV-Z]{25}$/i;

/** Error codes from the Error Handling catalogue, such as `VALIDATION_FAILED`. */
const ERROR_CODE = /^[A-Z][A-Z0-9_]{1,63}$/;

/** Dotted lower-case event names such as `http.request.completed`. */
const EVENT_NAME = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)*$/;
const MAX_EVENT_NAME_LENGTH = 64;

/** Deployable service names such as `api`, `worker` and `emergency-worker`. */
const SERVICE_NAME = /^[a-z][a-z0-9-]{0,62}$/;

const MAX_ROUTE_LENGTH = 200;

/**
 * One segment of a route template: a parameter (`:id` or `{id}`), a wildcard, or a static word that starts
 * with a letter and ends with at most two digits (`tickets`, `v1`, `l3`). Ids, roll numbers, ULIDs and email
 * addresses do not match, so a raw request path is rejected instead of being written out.
 */
const ROUTE_SEGMENT = /^(?::[A-Za-z][A-Za-z0-9_]*|\{[A-Za-z][A-Za-z0-9_]*\}|\*|[A-Za-z][A-Za-z_.-]*[0-9]{0,2})$/;

export function isUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID.test(value);
}

/** A Tenant id (a UUID) or {@link NO_TENANT}. */
export function isTenantIdValue(value: unknown): value is string {
  return value === NO_TENANT || isUuid(value);
}

/** Request ids are generated by the platform as ULIDs or UUIDs. Anything else may be caller-supplied text. */
export function isRequestIdValue(value: unknown): value is string {
  return typeof value === 'string' && (ULID.test(value) || UUID.test(value));
}

/** A route template such as `/api/v1/tickets/:id`, never the raw request path or query string. */
export function isRouteTemplate(value: unknown): value is string {
  if (typeof value !== 'string' || value.length === 0 || value.length > MAX_ROUTE_LENGTH || !value.startsWith('/')) {
    return false;
  }
  const segments = value.slice(1).split('/');
  return segments.every((segment, index) =>
    segment === '' ? index === segments.length - 1 : ROUTE_SEGMENT.test(segment),
  );
}

export function isErrorCode(value: unknown): value is string {
  return typeof value === 'string' && ERROR_CODE.test(value);
}

export function isEventName(value: unknown): value is string {
  return typeof value === 'string' && value.length <= MAX_EVENT_NAME_LENGTH && EVENT_NAME.test(value);
}

export function isServiceName(value: unknown): value is string {
  return typeof value === 'string' && SERVICE_NAME.test(value);
}

/** An HTTP status code: a whole number from 100 to 599. */
export function isHttpStatus(value: unknown): value is number {
  return typeof value === 'number' && Number.isInteger(value) && value >= 100 && value <= 599;
}

/** A non-negative, finite duration in milliseconds. */
export function isDurationMs(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0;
}

/** Tenant ids are lower-cased so that the same Tenant always produces the same field value and actorRef key. */
export function normalizeTenantId(tenantId: string): string {
  return tenantId.toLowerCase();
}
